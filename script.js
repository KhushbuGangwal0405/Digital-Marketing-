// ======================================================
// OPEN PROJECT
// ======================================================

function openProject(projectName) {

  const project = projects[projectName];

  if (!project) return;

  document.getElementById("projects").style.display = "none";

  document.getElementById("services").style.display = "block";

  document
    .getElementById("serviceDetail")
    .classList.remove("show");

  const detail =
    document.getElementById("projectDetail");

  detail.classList.add("show");

  document.getElementById("detailTag").textContent =
    project.tag;

  document.getElementById("detailTitle").textContent =
    project.title;

  document.getElementById("detailDescription").textContent =
    project.description;

  document.getElementById("detailOverview").textContent =
    project.overview;

  document.getElementById("detailSkills").textContent =
    project.skills;

  document.getElementById("detailGoal").textContent =
    project.goal;

  const workList =
    document.getElementById("detailWork");

  workList.innerHTML = "";

  project.work.forEach(function(item) {

    const li =
      document.createElement("li");

    li.textContent = item;

    workList.appendChild(li);

  });

  detail.scrollIntoView({
    behavior: "smooth"
  });

}


// ======================================================
// CLOSE PROJECT
// ======================================================

function closeProject() {

  document
    .getElementById("projectDetail")
    .classList.remove("show");

  document
    .getElementById("projects")
    .style.display = "block";

  document
    .getElementById("projects")
    .scrollIntoView({
      behavior: "smooth"
    });

}


